static __attribute__((noinline)) long step(char* b, long i) { b[i & 8191] = (char)i; return i * 3 + b[(i * 7) & 8191]; }

static __attribute__((noinline)) long big(long n) {
  char buf[8192];
  long s = n * 5 + 3;
  for (long i = 0; i < 8192; i++) buf[i] = (char)(i ^ n);
  for (long i = 0; i < n; i++) s += step(buf, i);
  return s + buf[n & 4095];
}

